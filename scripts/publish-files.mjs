// The hosted app's files, from the build (final-spec C8).
//
// The app is static: dist/ served from anywhere. One host, the Artifact page,
// supplies its own <head> and <body>, so it needs a wrapper holding page content
// only — publish/artifact.html — with the stylesheet inlined, published beside
// every script the bundle loads. Written by hand, that wrapper drifted twice: it
// kept an old dark stylesheet, and its file list left out the engine worker, so
// the hosted page could not read a file.
//
// This writes the wrapper FROM the build and prints the file list to publish
// with it, so neither can drift:
//
//   npm run build && node scripts/publish-files.mjs     (npm run publish:files)
//
// publishFiles() is also what the test checks: every script the bundle
// references is in the list.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, '..')

// -> { html, files: { 'app.js': 'dist/app.js', … }, missing: [] }
export function publishFiles(dist = join(root, 'dist')) {
  const css = readFileSync(join(dist, 'app.css'), 'utf8').trim()
  // Everything the build emitted except the page and the stylesheet (inlined).
  const names = readdirSync(dist, { recursive: true })
    .map((name) => String(name).replaceAll('\\', '/'))
    .filter((name) => /\.(js|json|wasm|woff2?)$/.test(name))
    .sort()
  const files = Object.fromEntries(names.map((name) => [name, `dist/${name}`]))
  // Every script file the bundle names must be one of them.
  const referenced = [...new Set(names.filter((name) => name.endsWith('.js'))
    .flatMap((name) => [...readFileSync(join(dist, name), 'utf8').matchAll(/["'`]((?:\.\/)?(?:assets\/)?app[\w.-]*\.js)["'`]/g)].map((m) => m[1].replace(/^\.\//, ''))))]
  const missing = referenced.filter((name) => !existsSync(join(dist, name)))
  const html = `<title>Data Contract Validator</title>

<!--
  Publish wrapper for the Artifact host, which supplies its own
  <!doctype>/<head>/<body> — so this file carries page content only.

  GENERATED by scripts/publish-files.mjs from the build: do not edit by hand.
  The stylesheet below is dist/app.css, inlined so the page paints its own
  ground before the bundle evaluates. Publish it with every file that script
  prints — the bundle AND the engine worker it loads.
-->
<style>
${css}

#root:empty::after {
  content: 'Loading…';
  display: block;
  padding: 32px 20px;
  color: #5b6770;
  font: 14px ui-sans-serif, system-ui, -apple-system, 'Segoe UI', sans-serif;
}
</style>

<div id="root"></div>
<script type="module" src="app.js"></script>
`
  return { html, files, referenced, missing }
}

if (import.meta.filename === process.argv[1]) {
  const out = publishFiles()
  if (out.missing.length > 0) {
    console.error(`The bundle references ${out.missing.join(', ')}, which the build did not emit.`)
    process.exit(1)
  }
  writeFileSync(join(root, 'publish', 'artifact.html'), out.html)
  console.log('Wrote publish/artifact.html. Publish it with these files:')
  console.log(JSON.stringify(out.files, null, 2))
}
