#!/usr/bin/env node
// The site's files for the Artifact host, from dist-site/ (the twin of
// publish-files.mjs, which does this for the app alone).
//
// The Artifact host wraps the ENTRY page in its own <!doctype>/<head>/<body>,
// so the entry must hold page content only; every other file is served as it
// is. This writes the entry — the home page's content with site.css inlined —
// to dist-site/artifact-entry.html, and prints the files to publish beside it:
// every other file of the build, the app under app/ included, at its own path.
//
//   npm run build && npm run build:site && npm run publish:site
//
// Then publish dist-site/artifact-entry.html with the printed `files`, to the
// site's existing artifact URL (a publish without it makes a new artifact).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const root = join(import.meta.dirname, '..')
export const ENTRY = 'artifact-entry.html'
// The artifact's name in the gallery; the site's own tab titles are unchanged.
export const ARTIFACT_TITLE = 'Plumbstep Website'

const TYPES = { '.woff2': 'font/woff2' }

// -> { entry: html, files: { 'packs.html': { from: 'dist-site/packs.html' }, … } }
export function publishSite(dir = join(root, 'dist-site')) {
  const index = readFileSync(join(dir, 'index.html'), 'utf8')
  const body = index.match(/<body>([\s\S]*)<\/body>/)?.[1]?.trim()
  if (!body) throw new Error(`${join(dir, 'index.html')} has no <body>: run npm run build:site first.`)
  const css = readFileSync(join(dir, 'site.css'), 'utf8').trim()
  const entry = `<title>${ARTIFACT_TITLE}</title>
<!--
  Artifact entry for the Plumbstep site: page content only, because the host
  supplies the document skeleton. GENERATED by scripts/publish-site.mjs from
  dist-site/index.html, with site.css inlined: do not edit by hand. Every other
  page is published beside it unchanged.
-->
<style>
${css}
</style>
${body}
`
  const files = {}
  for (const name of readdirSync(dir, { recursive: true, withFileTypes: true })) {
    if (!name.isFile()) continue
    const path = relative(dir, join(name.parentPath, name.name)).replaceAll('\\', '/')
    if (path === 'index.html' || path === ENTRY) continue
    const from = relative(root, join(dir, path)).replaceAll('\\', '/')
    const type = TYPES[path.slice(path.lastIndexOf('.'))]
    files[path] = type ? { from, contentType: type } : { from }
  }
  return { entry, files: Object.fromEntries(Object.entries(files).sort(([a], [b]) => a.localeCompare(b))) }
}

if (import.meta.filename === process.argv[1]) {
  const dir = join(root, 'dist-site')
  const { entry, files } = publishSite(dir)
  writeFileSync(join(dir, ENTRY), entry)
  if (!files['app/index.html']) console.error('No app under app/: run npm run build before npm run build:site, or the workspace links lead nowhere.')
  console.log(`Wrote dist-site/${ENTRY}. Publish it with these ${Object.keys(files).length} files:`)
  console.log(JSON.stringify(files, null, 2))
}
